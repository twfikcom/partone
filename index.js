function updateContent(lang) {
  const data = contentData[lang];
  
  if (!data) return;

  const setText = (id, text) => {
    const el = document.getElementById(id);
    if (el) el.textContent = text;
  };

  // Chapter 1 Content
  setText('title', data.title);
  setText('intro', data.intro);
  setText('subtitle1', data.subtitle1);
  setText('part1', data.part1);
  setText('subtitle2', data.subtitle2);
  setText('part2', data.part2);
  setText('part3', data.part3);
  setText('subtitle3', data.subtitle3);
  setText('conclusion', data.conclusion);
  setText('footer', data.footer);

  // Chapter 2 Content
  setText('c2-title', data.c2_title);
  setText('c2-intro', data.c2_intro);
  setText('c2-subtitle1', data.c2_subtitle1);
  setText('c2-part1', data.c2_part1);
  setText('c2-subtitle2', data.c2_subtitle2);
  setText('c2-part2', data.c2_part2);
  setText('c2-footer', data.c2_footer);

  // Buttons
  const btnC2 = document.querySelector('#btn-to-c2 span');
  const btnC1 = document.querySelector('#btn-to-c1 span');
  if(btnC2) btnC2.textContent = data.btn_to_c2;
  if(btnC1) btnC1.textContent = data.btn_to_c1;


  if (lang === 'ar') {
    document.body.classList.add('rtl');
    document.documentElement.lang = 'ar';
  } else {
    document.body.classList.remove('rtl');
    document.documentElement.lang = lang;
  }
}

function initAnimations() {
    const observerOptions = { threshold: 0.1 };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }
        });
    }, observerOptions);

    document.querySelectorAll('.animate-on-scroll').forEach(el => {
        observer.observe(el);
    });
}

function setupNavigation() {
    const btnToC2 = document.getElementById('btn-to-c2');
    const btnToC1 = document.getElementById('btn-to-c1');
    const c1 = document.getElementById('chapter-1');
    const c2 = document.getElementById('chapter-2');

    if (btnToC2 && c1 && c2) {
        btnToC2.addEventListener('click', () => {
            c1.style.display = 'none';
            c2.style.display = 'block';
            window.scrollTo({ top: 0, behavior: 'smooth' });
            
            // Re-trigger animations for the new content
            c2.querySelectorAll('.animate-on-scroll').forEach(el => {
                el.classList.remove('visible');
            });
            setTimeout(() => initAnimations(), 100);
        });
    }

    if (btnToC1 && c1 && c2) {
        btnToC1.addEventListener('click', () => {
            c2.style.display = 'none';
            c1.style.display = 'block';
            window.scrollTo({ top: 0, behavior: 'smooth' });
            
            // Re-trigger animations
            c1.querySelectorAll('.animate-on-scroll').forEach(el => {
                el.classList.add('visible');
            });
        });
    }
}

function init() {
    try {
        // Initialize Core Content
        const selector = document.getElementById('languageSelector');
        if (selector) {
            selector.addEventListener('change', (e) => {
                updateContent(e.target.value);
            });
            // Initial load
            updateContent('en');
        }

        // Initialize Scroll Animations
        initAnimations();

        // Initialize Navigation
        setupNavigation();
        
    } catch (e) {
        console.error("Initialization error:", e);
    } finally {
        // Hide Loading Screen ALWAYS
        const loader = document.getElementById('loading-screen');
        if (loader) {
            // Wait a moment for mystery effect, then fade out
            setTimeout(() => {
                loader.style.opacity = '0';
                setTimeout(() => {
                    loader.style.display = 'none';
                }, 1500);
            }, 2500);
        }
    }
}

// Ensure DOM is loaded
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
} else {
    init();
}