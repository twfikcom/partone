function initAnimations() {
    const observerOptions = { threshold: 0.1 };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }
        });
    }, observerOptions);

    document.querySelectorAll('.animate-on-scroll').forEach(el => {
        observer.observe(el);
    });
}

function setupNavigation() {
    const btnToC2 = document.getElementById('btn-to-c2');
    const btnC2toC1 = document.getElementById('btn-c2-to-c1');
    const btnToC3 = document.getElementById('btn-to-c3');
    const btnC3toC2 = document.getElementById('btn-c3-to-c2');
    const btnToC4 = document.getElementById('btn-to-c4');
    const btnC4toC3 = document.getElementById('btn-c4-to-c3');
    
    const c1 = document.getElementById('chapter-1');
    const c2 = document.getElementById('chapter-2');
    const c3 = document.getElementById('chapter-3');
    const c4 = document.getElementById('chapter-4');

    // Helper to switch chapters
    const switchChapter = (hide, show) => {
        if(hide) hide.style.display = 'none';
        if(show) {
            show.style.display = 'block';
            window.scrollTo({ top: 0, behavior: 'smooth' });
            // Re-trigger animations
            show.querySelectorAll('.animate-on-scroll').forEach(el => {
                el.classList.remove('visible');
            });
            setTimeout(() => initAnimations(), 100);
        }
    };

    if (btnToC2) btnToC2.addEventListener('click', () => switchChapter(c1, c2));
    if (btnC2toC1) btnC2toC1.addEventListener('click', () => switchChapter(c2, c1));
    if (btnToC3) btnToC3.addEventListener('click', () => switchChapter(c2, c3));
    if (btnC3toC2) btnC3toC2.addEventListener('click', () => switchChapter(c3, c2));
    if (btnToC4) btnToC4.addEventListener('click', () => switchChapter(c3, c4));
    if (btnC4toC3) btnC4toC3.addEventListener('click', () => switchChapter(c4, c3));
}

function init() {
    try {
        // Initialize Core Content
        const selector = document.getElementById('languageSelector');
        if (selector) {
            selector.addEventListener('change', (e) => {
                updateContent(e.target.value);
            });
            // Initial load
            updateContent('en');
        }

        // Initialize Scroll Animations
        initAnimations();

        // Initialize Navigation
        setupNavigation();
        
    } catch (e) {
        console.error("Initialization error:", e);
    } finally {
        // Hide Loading Screen ALWAYS
        const loader = document.getElementById('loading-screen');
        if (loader) {
            // Wait a moment for mystery effect, then fade out
            setTimeout(() => {
                loader.style.opacity = '0';
                setTimeout(() => {
                    loader.style.display = 'none';
                }, 1500);
            }, 2500);
        }
    }
}

// Ensure DOM is loaded
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
} else {
    init();
}